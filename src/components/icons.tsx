/**
 * The designs draw every icon with Lucide (layer names like `icon/inbox`, `Image (calendar-range)`), at a
 * 1.33px stroke on 16px. This module exposes Lucide icons under the names the pages already import, so
 * one file decides which Lucide glyph each name means. `weight` is accepted for old call sites: 'bold'
 * thickens the stroke, 'fill' fills only the house (the rail's active `icon/house-fill`), the rest is ignored.
 */
import type { ComponentType, CSSProperties } from 'react';
import * as L from 'lucide-react';

export type IconProps = {
  size?: number | string;
  weight?: 'thin' | 'light' | 'regular' | 'bold' | 'fill' | 'duotone';
  className?: string;
  style?: CSSProperties;
  color?: string;
  strokeWidth?: number;
  'aria-hidden'?: boolean;
  'aria-label'?: string;
};
export type Icon = ComponentType<IconProps>;

function wrap(G: L.LucideIcon, solid = false): Icon {
  const I = ({ size = '1em', weight, strokeWidth, ...p }: IconProps) => {
    const fill = solid && weight === 'fill';
    return <G size={size} strokeWidth={strokeWidth ?? (weight === 'bold' ? 2.5 : 2)} fill={fill ? 'currentColor' : 'none'} aria-hidden {...p} />;
  };
  I.displayName = G.displayName;
  return I;
}

